import streamlit as st
from docx import Document
from docx.enum.section import WD_ORIENT
from io import BytesIO

st.set_page_config(
    page_title="Химия ҚМЖ Генераторы - Кәсіби үлгі",
    page_icon="🧪",
    layout="wide"
)

st.title("🧪 Химия пәнінен Кәсіби ҚМЖ Генераторы (Стандартты үлгі)")
