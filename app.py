with st.form("pro_template_form"):
    st.subheader("Сабақ деректерін енгізіңіз:")
    
    col1, col2 = st.columns(2)
    with col1:
        org_name = st.text_input("Білім беру ұйымының атауы:", value="№ орта мектебі КММ")
        teacher_name = st.text_input("Педагогтің аты-жөні:", placeholder="Аты-жөніңіз")
        lesson_date = st.text_input("Күні:", value="28.08.2026")
        grade = st.selectbox("Сыныбы:", ["7-сынып", "8-сынып", "9-сынып", "10-сынып (ЖМБ)", "11-сынып (ЖМБ)"])
        topic = st.text_input("Сабақтың тақырыбы:", value="Атомда электрондардың таралуы")
    
    with col2:
        learning_obj = st.text_area("Оқу бағдарламасына сәйкес оқыту мақсаты:", value="8.1.3.1 - атомда электрондар ядродан арақашықтығы артқан сайын біртіндеп энергетикалық деңгейлер бойынша таралатынын түсіну")
        value_name = st.text_input("Құндылық:", value="ЕНБЕКҚОРЛЫҚ ЖӘНЕ КӘСІБИ БІЛІКТІЛІК АЙЫ")
        quote = st.text_input("Аптаның дәйексөзі:", value="Білім – қымбат қазына, Қанағат тұта білгенге азына (Музафар Әлімбаев)")

    submit_btn = st.form_submit_button(label="🚀 Кәсіби ҚМЖ Кестесін (Word) жасақтау")

if submit_btn:
    if not topic or not learning_obj:
        st.error("⚠️ Өтінемін, тақырып пен оқу мақсатын толтырыңыз!")
    else:
        st.success("✨ ҚМЖ кестесі сіздің үлгіңізге сай сәтті дайындалды!")

        doc = Document()
        
        # Парақты көлденең (Альбомный) ету
        section = doc.sections[0]
        new_width, new_height = section.page_height, section.page_width
        section.page_width = new_width
        section.page_height = new_height
        section.orientation = WD_ORIENT.LANDSCAPE

        # Тақырыптар
        doc.add_heading(f"{org_name}", level=3)
        doc.add_heading(f"ҚЫСҚА МЕРЗІМДІ САБАҚ ЖОСПАРЫ: {topic}", level=1)

        # 1. Ақпараттық кесте
        table_info = doc.add_table(rows=8, cols=2)
        table_info.style = 'Table Grid'
        
        info_data = [
            ("Бөлім", "Атом құрылысы"),
            ("Педагогтің аты-жөні", teacher_name if teacher_name else "[ ]"),
            ("Күні", lesson_date),
            ("Сыныбы", f"{grade} | Қатысушылар саны: 20 | Қатыспағандар саны: 0"),
            ("Сабақтың тақырыбы", topic),
            ("Оқу бағдарламасына сәйкес оқыту мақсаты", learning_obj),
            ("Сабақтың мақсаты", f"Атомда электрондар ядродан арақашықтығы артқан сайын біртіндеп энергетикалық деңгейлер бойынша таралатынын түсінеді."),
            ("Құндылық және дәйексөз", f"{value_name}\nДәйексөз: «{quote}»")
        ]

        for i, (k, v) in enumerate(info_data):
            table_info.cell(i, 0).text = k
            table_info.cell(i, 1).text = v

        doc.add_paragraph("\nСАБАҚТЫҢ БАРЫСЫ")

        # 2. Сабақ барысы кестесі (Суреттердегі құрылымға сай)
        table_course = doc.add_table(rows=5, cols=5)
        table_course.style = 'Table Grid'
        
        headers = ["Сабақтың кезеңі/уақыты", "Педагогтің әрекеті", "Оқушының әрекеті", "Бағалау", "Ресурстар"]
        for j, h in enumerate(headers):
            table_course.cell(0, j).text = h

        course_data = [
            ("Сабақтың басы\nҚызығушықты ояту.\n3 мин", 
             "1. Ұйымдастыру кезеңі: Оқушылармен сәлемдесіп, жағымды ахуал орнату.\n2. «Құпия сыйлық» әдісі арқылы топқа бөлу.\n3. «Адам әлемі» әдісі.\n4. Құндылықты дәріптейтін бейнежазба көрсету.", 
             "Салемдеседі, топтарға бөлінеді, қауіпсіздік ережелерін еске түсіреді.", 
             "«Алтын асық» әдісі", 
             "Оқулық, стикер, интерактивті тақта (Chatgpt, Claude AI, Diffit арқылы жасалған бейнежазба)"),
            
            ("Үй тапсырмасын пысықтау\n5 мин", 
             "1. «Перфокарта» әдісі арқылы өткенді пысықтау.\n2. «Сұрақ-жауап» әдісі: Химиялық элемент дегеніміз не? Атом құрылысы қандай?", 
             "Перфокартаны толтырады, сұрақтарға жауап беріп, атом ядросы мен электрондарды сипаттайды.", 
             "Қалыптастырушы бағалау: «Жарайсың! Керемет!»", 
             "Интерактивті тақта, перфокарталар"),
            
            ("Жаңа сабаққа кіріспе\n5 мин", 
             f"1. Кіріспе сұрақ: Атомдағы электрондар қалай орналасады?\n2. {topic} бойынша теориялық түсінік беру.", 
             "Сұрақтарға жауап беріп, атомның энергетикалық деңгейлерін анықтайды.", 
             "Бағалау: «Өзін-өзі бағалау»", 
             "Оқулық, презентация, жұмыс парақтары"),
            
            ("Негізгі бөлім\nТоптық және жеке жұмыс\n25 мин", 
             "1. **1-тапсырма («Жалғасын тап»):** Оқулықтағы тапсырманы орындау.\n2. **2-тапсырма (Топтық - ВЕНН диаграммасы):** Изотоптарды салыстыру және сәйкестендіру.\n3. **3-тапсырма (Жеке):** Деңгейлік тапсырмалар (А, В, С).\n4. **Функционалдық сауаттылық:** Практикалық жағдаятты талдау.", 
             "Топпен және жеке тапсырмаларды орындайды, бор диаграммалары мен деңгейлік есептерді шығарады.", 
             "**Критерий:** Электрондардың таралуын анықтайды.\n**Дескриптор:**\n- Энергетикалық деңгейді табады - 1 б.\n- Формула қолданады - 2 б.\n- Тұжырым жасайды - 2 б.\n**Жалпы балл: 5 б.**", 
             "Үлестірмелі материалдар, плакаттар, интербелсенді тақта")
        ]

        for row_idx, row_content in enumerate(course_data, start=1):
            for col_idx, text in enumerate(row_content):
                table_course.cell(row_idx, col_idx).text = text

        # 3. Рефлексия және Үй тапсырмасы
        doc.add_heading("РЕФЛЕКСИЯ ЖӘНЕ ҮЙ ТАПСЫРМАСЫ", level=2)
        table_ref = doc.add_table(rows=3, cols=5)
        table_ref.style = 'Table Grid'
        
        ref_headers = ["Сабақтың соңы", "Педагогтің әрекеті", "Оқушының әрекеті", "Бағалау", "Ресурстар"]
        for j, h in enumerate(ref_headers):
            table_ref.cell(0, j).text = h

        ref_data = [
            ("Рефлексия\n5 мин", "Рефлексия «Үш асық» әдісі арқылы кері байланыс жасауды ұйымдастыру.", "Бүгінгі сабақты қалай түсінгенін үш асық арқылы белгілеп, кері байланыс береді.", "Өзін-өзі бағалау", "Интерактивті тақта, асықтар суреті"),
            ("Үй тапсырмасы", "§1, №7 тапсырма (6-бет). Тақырып бойынша эссе жазу және қосымша интернет материалдарын оқу.", "Үй тапсырмасын күнделікке жазып алады.", "Критериалды бағалау", "Күнделік, оқулық")
        ]

        for row_idx, row_content in enumerate(ref_data, start=1):
            for col_idx, text in enumerate(row_content):
                table_ref.cell(row_idx, col_idx).text = text

        buffer = BytesIO()
        doc.save(buffer)
        buffer.seek(0)

        st.download_button(
            label="📥 Кәсіби ҚМЖ Кестесін жүктеп алу (.docx)",
            data=buffer,
            file_name=f"QMZ_Standard_{topic[:15]}.docx",
            mime="application/vnd.openxmlformats-officedocument.wordprocessingml.document"
        )
